    TANK_LEVEL      NUMBER(10, 4)   NOT NULL,   -- 告警时液位（m³）
    LEVEL_RATIO     NUMBER(6, 4)    NOT NULL,   -- 告警时液位占比
    ALERT_MESSAGE   VARCHAR2(500)   NOT NULL,   -- 告警描述
    IS_HANDLED      NUMBER(1)       NOT NULL,   -- 是否已处理（1:是 0:否）
    HANDLED_BY      VARCHAR2(100),
    HANDLED_TIME    TIMESTAMP,
    HANDLE_REMARK   VARCHAR2(500),
    CREATE_TIME     TIMESTAMP       NOT NULL,
    CONSTRAINT PK_WW_ALERT_LOG          PRIMARY KEY (ALERT_ID)
);

COMMENT ON TABLE  WW_ALERT_LOG               IS '告警记录表';
COMMENT ON COLUMN WW_ALERT_LOG.ALERT_ID       IS '主键，由序列 SEQ_ALERT_LOG 自增';
COMMENT ON COLUMN WW_ALERT_LOG.SCHEDULE_ID    IS '调度批次号，关联 WW_SCHEDULE_RESULT';
COMMENT ON COLUMN WW_ALERT_LOG.ALERT_TIME     IS '告警时间';
COMMENT ON COLUMN WW_ALERT_LOG.ALERT_LEVEL    IS '告警级别（2:告警 3:紧急）';
COMMENT ON COLUMN WW_ALERT_LOG.TANK_LEVEL     IS '告警时液位（m³）';
COMMENT ON COLUMN WW_ALERT_LOG.LEVEL_RATIO    IS '告警时液位占比';
COMMENT ON COLUMN WW_ALERT_LOG.ALERT_MESSAGE  IS '告警描述';
COMMENT ON COLUMN WW_ALERT_LOG.IS_HANDLED     IS '是否已处理（1:是 0:否）';
COMMENT ON COLUMN WW_ALERT_LOG.HANDLED_BY     IS '处理人';
COMMENT ON COLUMN WW_ALERT_LOG.HANDLED_TIME   IS '处理时间';
COMMENT ON COLUMN WW_ALERT_LOG.HANDLE_REMARK  IS '处理备注';
COMMENT ON COLUMN WW_ALERT_LOG.CREATE_TIME    IS '记录创建时间';


-- ------------------------------------------------------------
-- 表6：调度输入快照表 WW_SCHEDULE_INPUT
-- 存储每次调度运行时的系统级配置快照，便于复盘、调试和AI训练
-- ------------------------------------------------------------
CREATE TABLE WW_SCHEDULE_INPUT (
    INPUT_ID                NUMBER(20)      NOT NULL,
    SCHEDULE_ID             VARCHAR2(50)    NOT NULL,   -- 调度批次号，关联 WW_SCHEDULE_RESULT
    SCHEDULE_TIME           TIMESTAMP       NOT NULL,   -- 调度执行时间
    TANK_CAPACITY           NUMBER(10, 4)   NOT NULL,   -- 储罐容量 V（m³）
    PROCESS_CAPACITY        NUMBER(10, 4)   NOT NULL,   -- 处理总能力 C（m³/h）
    SCHEDULE_INTERVAL_MIN   NUMBER(10)      NOT NULL,   -- 调度周期（分钟）
    SAFE_RATIO              NUMBER(6, 4)    NOT NULL,   -- 安全容量系数
    WARNING_RATIO           NUMBER(6, 4)    NOT NULL,   -- 预警阈值
    ALERT_RATIO             NUMBER(6, 4)    NOT NULL,   -- 告警阈值
    EMERGENCY_RATIO         NUMBER(6, 4)    NOT NULL,   -- 紧急阈值
    MIN_RATE_RATIO          NUMBER(6, 4)    NOT NULL,   -- 弹性压缩最低保留比例
    PROCESS_BUFFER_RATIO    NUMBER(6, 4)    NOT NULL,   -- 处理能力缓冲系数
    TANK_LEVEL              NUMBER(10, 4)   NOT NULL,   -- 调度时储罐液位（m³）
    LEVEL_RATIO             NUMBER(6, 4)    NOT NULL,   -- 调度时液位占比
    ZONE                    VARCHAR2(20)    NOT NULL,   -- 液位区间（NORMAL/WARNING/ALERT/EMERGENCY）
    ELASTIC_K               NUMBER(6, 4),               -- 弹性系数 k（预警区间有效）
    CAPACITY_LIMIT          NUMBER(10, 4),              -- 容量约束上限计算值（m³/h）
    PROCESS_LIMIT           NUMBER(10, 4),              -- 处理能力约束上限计算值（m³/h）
    EFFECTIVE_LIMIT         NUMBER(10, 4),              -- 实际生效约束上限
    WORKSHOP_COUNT          NUMBER(5)       NOT NULL,   -- 本次调度启用车间数量
    CREATE_TIME             TIMESTAMP       NOT NULL,
    CONSTRAINT PK_WW_SCHEDULE_INPUT    PRIMARY KEY (INPUT_ID)
);

COMMENT ON TABLE  WW_SCHEDULE_INPUT                    IS '调度输入快照表（系统级配置）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.INPUT_ID           IS '主键，由序列 SEQ_SCHEDULE_INPUT 自增';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.SCHEDULE_ID        IS '调度批次号，关联 WW_SCHEDULE_RESULT';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.SCHEDULE_TIME      IS '调度执行时间';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.TANK_CAPACITY      IS '储罐容量 V（m³）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.PROCESS_CAPACITY   IS '处理总能力 C（m³/h）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.SCHEDULE_INTERVAL_MIN IS '调度周期（分钟）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.SAFE_RATIO         IS '安全容量系数';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.WARNING_RATIO      IS '预警阈值';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.ALERT_RATIO        IS '告警阈值';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.EMERGENCY_RATIO    IS '紧急阈值';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.MIN_RATE_RATIO     IS '弹性压缩最低保留比例';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.PROCESS_BUFFER_RATIO IS '处理能力缓冲系数';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.TANK_LEVEL         IS '调度时储罐液位（m³）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.LEVEL_RATIO        IS '调度时液位占比';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.ZONE               IS '液位区间（NORMAL/WARNING/ALERT/EMERGENCY）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.ELASTIC_K          IS '弹性系数 k（预警区间有效，其他为NULL）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.CAPACITY_LIMIT     IS '容量约束上限计算值（m³/h）';
COMMENT ON COLUMN WW_SCHEDULE_INPUT.PROCESS_LIMIT      IS '处理能力约束上限计算值（m³/h）';
