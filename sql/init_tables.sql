CREATE INDEX IDX_ALERT_LEVEL
    ON WW_ALERT_LOG (ALERT_LEVEL);

-- WW_ALERT_LOG：按时间范围查询
CREATE INDEX IDX_ALERT_TIME
    ON WW_ALERT_LOG (ALERT_TIME);

-- WW_ALERT_LOG：按调度批次号查询
CREATE INDEX IDX_ALERT_SCHEDULE_ID
    ON WW_ALERT_LOG (SCHEDULE_ID);

