-- ------------------------------------------------------------
-- 表1：车间基础信息表 WW_WORKSHOP_INFO
-- ------------------------------------------------------------
CREATE TABLE WW_WORKSHOP_INFO (
    WORKSHOP_ID         VARCHAR2(20)    NOT NULL,
    WORKSHOP_NAME       VARCHAR2(100)   NOT NULL,
    MAX_DISCHARGE_RATE  NUMBER(10, 4)   NOT NULL,   -- 最大排放速率（m³/h）
    MIN_DISCHARGE_RATE  NUMBER(10, 4)   NOT NULL,   -- 最小排放速率（m³/h），管道最低流量要求
    PRIORITY_WEIGHT     NUMBER(6, 4)    NOT NULL,   -- 优先级权重（默认 1.0，值越大优先级越高）
    IS_ACTIVE           NUMBER(1)       NOT NULL,   -- 是否启用（1:是 0:否）
    REMARK              VARCHAR2(500),
    CREATE_TIME         TIMESTAMP       NOT NULL,
    UPDATE_TIME         TIMESTAMP       NOT NULL,
    CONSTRAINT PK_WW_WORKSHOP_INFO    PRIMARY KEY (WORKSHOP_ID),
    CONSTRAINT CHK_WORKSHOP_IS_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CHK_WORKSHOP_MAX_RATE CHECK (MAX_DISCHARGE_RATE > 0),
    CONSTRAINT CHK_WORKSHOP_MIN_RATE CHECK (MIN_DISCHARGE_RATE >= 0),
    CONSTRAINT CHK_WORKSHOP_WEIGHT CHECK (PRIORITY_WEIGHT > 0),
    CONSTRAINT CHK_WORKSHOP_RATE_ORD CHECK (MAX_DISCHARGE_RATE >= MIN_DISCHARGE_RATE)
);

COMMENT ON TABLE  WW_WORKSHOP_INFO                    IS '车间基础信息表';
COMMENT ON COLUMN WW_WORKSHOP_INFO.WORKSHOP_ID        IS '车间编号，主键';
COMMENT ON COLUMN WW_WORKSHOP_INFO.WORKSHOP_NAME      IS '车间名称';
COMMENT ON COLUMN WW_WORKSHOP_INFO.MAX_DISCHARGE_RATE IS '最大排放速率（m³/h）';
COMMENT ON COLUMN WW_WORKSHOP_INFO.MIN_DISCHARGE_RATE IS '最小排放速率（m³/h），管道最低流量要求';
COMMENT ON COLUMN WW_WORKSHOP_INFO.PRIORITY_WEIGHT    IS '优先级权重（默认1.0，值越大优先级越高）';
COMMENT ON COLUMN WW_WORKSHOP_INFO.IS_ACTIVE          IS '是否启用（1:是 0:否）';
COMMENT ON COLUMN WW_WORKSHOP_INFO.REMARK             IS '备注';
COMMENT ON COLUMN WW_WORKSHOP_INFO.CREATE_TIME        IS '创建时间';
COMMENT ON COLUMN WW_WORKSHOP_INFO.UPDATE_TIME        IS '最后更新时间';


-- ------------------------------------------------------------
-- 表2：系统参数配置表 WW_SYSTEM_CONFIG
