-- ------------------------------------------------------------
-- 表3：储罐状态表 WW_TANK_STATUS
-- ------------------------------------------------------------
CREATE TABLE WW_TANK_STATUS (
    STATUS_ID       NUMBER(20)      NOT NULL,
    RECORD_TIME     TIMESTAMP       NOT NULL,
    CURRENT_LEVEL   NUMBER(10, 4)   NOT NULL,   -- 当前液位（m³）
    LEVEL_RATIO     NUMBER(6, 4)    NOT NULL,   -- 液位占比（= 当前液位 / 储罐容量）
    TANK_STATUS     VARCHAR2(20)    NOT NULL,   -- NORMAL / WARNING / ALERT / EMERGENCY
    PREDICTED_LEVEL NUMBER(10, 4),              -- 下周期预测液位（m³），可为空
    INPUT_TYPE      VARCHAR2(20)    NOT NULL,   -- MANUAL / AUTO
    INPUT_BY        VARCHAR2(100),              -- 录入人，自动采集时可为空
    CREATE_TIME     TIMESTAMP       NOT NULL,
    CONSTRAINT PK_WW_TANK_STATUS        PRIMARY KEY (STATUS_ID)
);

COMMENT ON TABLE  WW_TANK_STATUS                 IS '储罐状态表';
COMMENT ON COLUMN WW_TANK_STATUS.STATUS_ID        IS '主键，由序列 SEQ_TANK_STATUS 自增';
COMMENT ON COLUMN WW_TANK_STATUS.RECORD_TIME      IS '记录时间';
COMMENT ON COLUMN WW_TANK_STATUS.CURRENT_LEVEL    IS '当前液位（m³）';
COMMENT ON COLUMN WW_TANK_STATUS.LEVEL_RATIO      IS '液位占比（= 当前液位 / 储罐容量）';
COMMENT ON COLUMN WW_TANK_STATUS.TANK_STATUS      IS '液位状态（NORMAL/WARNING/ALERT/EMERGENCY）';
COMMENT ON COLUMN WW_TANK_STATUS.PREDICTED_LEVEL  IS '下周期预测液位（m³），告警/紧急区间时为 L - C×T';
COMMENT ON COLUMN WW_TANK_STATUS.INPUT_TYPE       IS '录入方式（MANUAL:人工 / AUTO:传感器，预留）';
COMMENT ON COLUMN WW_TANK_STATUS.INPUT_BY         IS '录入人（自动采集时为空）';
COMMENT ON COLUMN WW_TANK_STATUS.CREATE_TIME      IS '记录创建时间';


-- ------------------------------------------------------------
-- 表4：调度结果表 WW_SCHEDULE_RESULT
-- ------------------------------------------------------------
CREATE TABLE WW_SCHEDULE_RESULT (
    RESULT_ID           NUMBER(20)      NOT NULL,
    SCHEDULE_ID         VARCHAR2(50)    NOT NULL,   -- 调度批次号（UUID），同一次调度各车间相同
    SCHEDULE_TIME       TIMESTAMP       NOT NULL,   -- 调度执行时间
    WORKSHOP_ID         VARCHAR2(20)    NOT NULL,   -- 车间编号
    ALLOWED_RATE        NUMBER(10, 4)   NOT NULL,   -- 建议排放速率（m³/h），即决策变量 r_i
    ALLOWED_VOLUME      NUMBER(10, 4)   NOT NULL,   -- 推算排放量（m³）= ALLOWED_RATE × T
    TANK_LEVEL_BEFORE   NUMBER(10, 4)   NOT NULL,   -- 调度前液位（m³）
    SCHEDULE_STATUS     VARCHAR2(20)    NOT NULL,   -- NORMAL / WARNING / ALERT / EMERGENCY
    SOLVER_STATUS       VARCHAR2(50)    NOT NULL,   -- Optimal / Infeasible / SKIPPED / Timeout
    CREATE_TIME         TIMESTAMP       NOT NULL,
    CONSTRAINT PK_WW_SCHEDULE_RESULT    PRIMARY KEY (RESULT_ID)
);

COMMENT ON TABLE  WW_SCHEDULE_RESULT                   IS '调度结果表（建议值，不具备控制指令属性）';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.RESULT_ID          IS '主键，由序列 SEQ_SCHEDULE_RESULT 自增';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.SCHEDULE_ID        IS '调度批次号（UUID），同一次调度所有车间共享';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.SCHEDULE_TIME      IS '调度执行时间';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.WORKSHOP_ID        IS '车间编号，关联 WW_WORKSHOP_INFO';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.ALLOWED_RATE       IS '本周期建议排放速率（m³/h），即决策变量 r_i';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.ALLOWED_VOLUME     IS '本周期推算排放量（m³）= ALLOWED_RATE × T';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.TANK_LEVEL_BEFORE  IS '调度前储罐液位（m³）';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.SCHEDULE_STATUS    IS '调度状态（NORMAL/WARNING/ALERT/EMERGENCY）';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.SOLVER_STATUS      IS '求解器状态（Optimal/Infeasible/SKIPPED/Timeout）';
COMMENT ON COLUMN WW_SCHEDULE_RESULT.CREATE_TIME        IS '记录创建时间';


-- ------------------------------------------------------------
-- 表5：告警记录表 WW_ALERT_LOG
-- ------------------------------------------------------------
CREATE TABLE WW_ALERT_LOG (
    ALERT_ID        NUMBER(20)      NOT NULL,
