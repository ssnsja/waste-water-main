CREATE INDEX IDX_SCHEDULE_BATCH
    ON WW_SCHEDULE_RESULT (SCHEDULE_ID);

-- WW_SCHEDULE_RESULT：按时间范围查询历史记录
CREATE INDEX IDX_SCHEDULE_TIME
    ON WW_SCHEDULE_RESULT (SCHEDULE_TIME);

